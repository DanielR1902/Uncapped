@dataclass
class BuildPlan:
    name: str
    creation_mode: str  # "Budget" | "Workload" | "Free"
    workload_profile: str | None = None
    tier: str | None = None
    budget_ceiling: float | None = None


def _generate_build_state(plan: BuildPlan, rng: random.Random) -> BuildState:
    if plan.creation_mode == "Budget":
        return solvers.initialize_budget_build(plan.budget_ceiling, fill_peripherals_with_surplus=True)
    if plan.creation_mode == "Workload":
        return solvers.allocate_workload_baseline(
            plan.workload_profile, target_tier=plan.tier, include_peripherals=True
        )
    return _generate_free_build(rng)


def _generate_free_build(rng: random.Random) -> BuildState:
    """Mode C freestyle: walk every category, at each step picking a random
    candidate from `get_compatible_candidates` — which re-checks the WHOLE
    hypothetical build via `evaluate_build`, not just the new part against
    one neighbor — so the final build_state is guaranteed fully compatible
    by construction, the same guarantee every other creation mode has."""
    build_state: BuildState = {}
    for category in solvers.CATEGORY_ORDER:
        candidates = solvers.get_compatible_candidates(category, build_state)
        if candidates:
            build_state[category] = rng.choice(candidates)
    for category in solvers.PERIPHERAL_CATEGORIES:
        if rng.random() < 0.7:
            candidates = solvers.get_compatible_candidates(category, build_state)
            if candidates:
                build_state[category] = rng.choice(candidates)
    return build_state


def _build_total_cost(build_state: BuildState) -> float:
    return sum(component.price_usd for component in build_state.values())


def _create_build(plan: BuildPlan, user_id: int, rng: random.Random) -> tuple[Build, BuildState] | None:
    build_state = _generate_build_state(plan, rng)
    report = evaluate_build(build_state)
    if not report.is_compatible:
        print(f"  WARNING: '{plan.name}' has compatibility issues, NOT persisting: {report.issues}")
        return None
    total_cost = _build_total_cost(build_state)
    bottleneck_pct, _direction = scoring.bottleneck_percentage_baseline(build_state)
    synergy_score = scoring.heuristic_synergy_score(report.compatibility_score, bottleneck_pct)
    components = [
        builds_repo.BuildComponentInput(component_id=component.id, quantity=1)
        for component in build_state.values()
    ]
    build = builds_repo.create_build(
        user_id=user_id,
        name=plan.name,
        creation_mode=plan.creation_mode,
        components=components,
        total_cost=total_cost,
        compatibility_score=report.compatibility_score,
        workload_profile=plan.workload_profile,
        workload_tier=plan.tier,
        budget_ceiling=plan.budget_ceiling,
        synergy_score=synergy_score,
        bottleneck_percentage=bottleneck_pct,
        is_public=False,
    )
    return build, build_state


