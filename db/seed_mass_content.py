def _fmt_names(build_state: BuildState) -> dict[str, str]:
    cpu = build_state.get("CPU")
    gpu = build_state.get("GPU")
    return {
        "cpu": cpu.name if cpu else "an unnamed CPU",
        "gpu": gpu.name if gpu else "an unnamed GPU",
    }


def _profile_word(build: Build) -> str:
    return f"{build.workload_profile.lower()} " if build.workload_profile else ""


def _publish(build: Build, build_state: BuildState, flair: str, rng: random.Random) -> int:
    names = _fmt_names(build_state)
    title_pool = _RATE_TITLE_TEMPLATES if flair == FLAIR_RATE else _HELP_TITLE_TEMPLATES
    note_pool = _RATE_NOTE_TEMPLATES if flair == FLAIR_RATE else _HELP_NOTE_TEMPLATES
    title = rng.choice(title_pool).format(
        cpu=names["cpu"], gpu=names["gpu"], total=build.total_cost, profile_word=_profile_word(build)
    )
    notes = rng.choice(note_pool).format(
        cpu=names["cpu"], gpu=names["gpu"], total=build.total_cost, profile_word=_profile_word(build)
    )
    builds_repo.set_public(build.id, True)
    post = community_repo.create_post(build_id=build.id, user_id=build.user_id, title=title, author_notes=notes, flair=flair)
    return post.id


def _add_comments(
    post_id: int, build_state: BuildState, total_cost: float, user_ids: list[int], rng: random.Random
) -> None:
    names = _fmt_names(build_state)
    comment_count = rng.randint(2, 5)
    posted_ids: list[int] = []
    for _ in range(comment_count):
        author_id = rng.choice(user_ids)
        parent_id = None
        if posted_ids and rng.random() < 0.5:
            parent_id = rng.choice(posted_ids)
        pool = _REPLY_COMMENT_TEMPLATES if parent_id is not None else _ROOT_COMMENT_TEMPLATES
        content = rng.choice(pool).format(cpu=names["cpu"], gpu=names["gpu"], total=total_cost)
        comment = community_repo.add_comment(
            post_id=post_id, user_id=author_id, content=content, parent_comment_id=parent_id
        )
        posted_ids.append(comment.id)


def _wipe_dynamic_content() -> None:
    with session_scope() as session:
        session.execute(delete(CommunityComment))
        session.execute(delete(CommunityPost))
        session.execute(delete(BuildComponent))
        session.execute(delete(Build))


def run_mass_content_seed() -> dict:
    init_db()
    run_catalog_seed()  # idempotent; ensures catalog components exist to reference

    admin = users_repo.get_by_username("admin")
    if admin is None:
        raise RuntimeError(
            "admin user not found — run `python -m db.seed_demo` first to establish "
            "the standing admin login and 5 persona users this script reseeds content for."
        )
    persona_users = {username: users_repo.get_by_username(username) for username in DEMO_USERNAMES}
    missing = [username for username, user in persona_users.items() if user is None]
    if missing:
        raise RuntimeError(f"persona users not found: {missing} — run `python -m db.seed_demo` first.")

    _wipe_dynamic_content()

    rng = random.Random(_SEED)
    all_user_ids = [admin.id] + [user.id for user in persona_users.values()]

    admin_builds: list[tuple[Build, BuildState]] = []
    for plan in ADMIN_PLANS:
        result = _create_build(plan, admin.id, rng)
        if result is not None:
            admin_builds.append(result)

    persona_builds: dict[str, list[tuple[Build, BuildState]]] = {}
    for username, user in persona_users.items():
        built: list[tuple[Build, BuildState]] = []
        for plan in _PERSONA_PLANS[username]:
            result = _create_build(plan, user.id, rng)
            if result is not None:
                built.append(result)
        persona_builds[username] = built

    published_count = 0
    for index in _ADMIN_PUBLISH_INDICES:
        if index >= len(admin_builds):
            continue
        build, build_state = admin_builds[index]
        flair = FLAIR_RATE if published_count % 2 == 0 else FLAIR_HELP
        post_id = _publish(build, build_state, flair, rng)
        _add_comments(post_id, build_state, build.total_cost, all_user_ids, rng)
        published_count += 1

    for username, built in persona_builds.items():
        publish_n = _PERSONA_PUBLISH_COUNTS[username]
        for build, build_state in built[:publish_n]:
            flair = FLAIR_RATE if published_count % 2 == 0 else FLAIR_HELP
            post_id = _publish(build, build_state, flair, rng)
            _add_comments(post_id, build_state, build.total_cost, all_user_ids, rng)
            published_count += 1

    total_builds = len(admin_builds) + sum(len(v) for v in persona_builds.values())
    return {
        "total_builds": total_builds,
        "admin_builds": len(admin_builds),
        "persona_builds": {k: len(v) for k, v in persona_builds.items()},
        "published": published_count,
    }


if __name__ == "__main__":
    summary = run_mass_content_seed()
    print(f"Seeded {summary['total_builds']} builds ({summary['admin_builds']} admin).")
    print(f"Published {summary['published']} posts with threaded comments.")
    print(f"Persona build counts: {summary['persona_builds']}")
