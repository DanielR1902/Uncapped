"""Mass content reset & seeder — a strictly data-only operator script (see
this repo's root CLAUDE.md guardrail: no application/engine/UI/theme/config
code is touched by this file's existence or by running it).

Performs a hard wipe of the three dynamic content tables (`builds`,
`community_posts`, `community_comments` — cascades to `build_components` and
comment replies via the real FK `ondelete="CASCADE"` constraints, enabled at
the connection level by db/database.py's `_enable_sqlite_foreign_keys`) while
leaving every `users` row (including the standing "admin" login and the 5
persona accounts from db/seed_demo.py) completely untouched, then reseeds:

- 70 total builds: 15 owned by admin (5 Budget-mode at 5 distinct ceilings,
  5 Workload-mode at 5 distinct profile/tier combos, 5 Free-mode "freestyle"
  builds), 55 distributed 11-each across the 5 persona users.
- Exactly 30 of those 70 published to the community feed (8 of admin's 15,
  22 of the 55 persona builds), flair balanced ~15/~15 between "Rate My
  Build" and "Looking for Help", each with a distinct, data-derived
  author_notes string.
- 2-5 comments (a mix of root-level and nested replies via
  `parent_comment_id`) on every one of those 30 published posts, authored by
  a realistic mix of the 6 existing users.

Every generated build is verified compatible (`engine.compatibility.
evaluate_build(...).is_compatible`) before it is ever persisted — Free-mode
builds are generated by walking `engine.solvers.CATEGORY_ORDER`/
`PERIPHERAL_CATEGORIES` and, at each step, choosing only from
`solvers.get_compatible_candidates(...)` (itself a full-build re-check, not
just a pairwise one), the same guarantee `db/seed_admin_builds.py`'s own
hand-picked Free-mode plans rely on `evaluate_build` for. Budget/Workload
builds reuse `engine.solvers.initialize_budget_build`/
`allocate_workload_baseline` directly, which already guarantee compatibility
by construction. No score is ever computed via `llm/` — same
network-independent, `db/seed_admin_builds.py`-established convention.

Run directly: `python -m db.seed_mass_content`
"""
